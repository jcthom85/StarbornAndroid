// Browser smoke checks using an isolated headless Chrome profile and the DevTools protocol.
// Run with an already-serving URL: node sites/starborn-playtest/check.mjs <url>
import { spawn } from 'node:child_process';
import { mkdtemp, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import assert from 'node:assert/strict';
const url = process.argv[2] || 'http://127.0.0.1:4173/';
const profile = await mkdtemp(path.join(tmpdir(), 'starborn-guide-qa-'));
const chromePath = process.env.CHROME_PATH || (process.platform === 'darwin' ? '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome' : process.platform === 'win32' ? 'C:/Program Files/Google/Chrome/Application/chrome.exe' : 'google-chrome');
const chrome = spawn(chromePath, ['--headless=new', '--remote-debugging-port=9427', `--user-data-dir=${profile}`, '--no-first-run', '--no-default-browser-check', 'about:blank'], { stdio: 'ignore', windowsHide: true });
let socket;
try {
  let targets;
  for (let i = 0; i < 50; i++) {
    try { targets = await (await fetch('http://127.0.0.1:9427/json')).json(); break; } catch { await new Promise(resolve => setTimeout(resolve, 200)); }
  }
  assert(targets?.length, 'Chrome starts');
  socket = new WebSocket(targets.find(t => t.type === 'page').webSocketDebuggerUrl);
  await new Promise((resolve, reject) => { socket.onopen = resolve; socket.onerror = reject; });
  let serial = 0;
  const pending = new Map();
  const errors = [];
  socket.onmessage = event => {
    const msg = JSON.parse(event.data);
    if (msg.method === 'Runtime.exceptionThrown') errors.push(msg.params.exceptionDetails);
    if (msg.id && pending.has(msg.id)) { const { resolve, reject } = pending.get(msg.id); pending.delete(msg.id); if (msg.error) reject(new Error(JSON.stringify(msg.error))); else resolve(msg.result); }
  };
  const send = (method, params = {}) => new Promise((resolve, reject) => { const id = ++serial; pending.set(id, { resolve, reject }); socket.send(JSON.stringify({ id, method, params })); });
  const evaluate = async expression => { const result = await send('Runtime.evaluate', { expression, returnByValue: true, awaitPromise: true }); if (result.exceptionDetails) throw new Error(JSON.stringify(result.exceptionDetails)); return result.result.value; };
  await send('Runtime.enable');
  await send('Page.enable');
  await send('Emulation.setDeviceMetricsOverride', { width: 1440, height: 1000, deviceScaleFactor: 1, mobile: false });
  await send('Page.navigate', { url: url.replace(/#.*$/, '') + '#world-2/' });
  async function waitFor(expression) { for (let i = 0; i < 100; i++) { if (await evaluate(expression)) return; await new Promise(resolve => setTimeout(resolve, 100)); } throw new Error(`Timed out: ${expression}`); }
  await waitFor('document.querySelector("#article h2") !== null');
  await waitFor('document.querySelector(".brand-logo")?.naturalWidth > 0');
  assert.equal(await evaluate('GUIDES.length'), 4);
  assert.equal(await evaluate('world'), 2, 'world-2 root link selects World 2 on a fresh visit');
  assert.equal(await evaluate('GUIDES[1].sections.some(s => s.blocks.some(b => b.text.includes("report_to_zeke")))'), true, 'World 2 includes the current Botanist return task');
  await evaluate(`state.worlds[1] = {checked:[GUIDES[0].sections.flatMap(s=>s.blocks).filter(b=>b.step!==null).at(-1).id],section:0,scroll:0}; state.worlds[2].checked=[GUIDES[1].sections.flatMap(s=>s.blocks).find(b=>b.step!==null).id]; state.worlds[3]={checked:['old-world3-step'],section:0,scroll:0}; save();`);
  const preservedProgress = await evaluate('JSON.stringify([state.worlds[1],state.worlds[2],state.worlds[3]])');
  await send('Page.navigate', { url: url.replace(/#.*$/, '') + '#world-3/' });
  await waitFor('typeof world !== "undefined" && world === 3 && document.querySelector("#article h2") !== null');
  assert.equal(await evaluate('GUIDES[2].sections.some(s => s.blocks.some(b => b.text.includes("recover_bridge_relic")))'), false);
  assert.equal(await evaluate('GUIDES[2].sections.some(s => s.blocks.some(b => b.text.includes("defeat_administrator")))'), true, 'World 3 current quest catalog');
  assert.equal(await evaluate('GUIDES[2].sections.some(s => s.title.includes("How to follow"))'), true, 'World 3 rebuilt route is present');
  assert.equal(await evaluate('GUIDES[2].sections.flatMap(s => s.blocks).filter(b => b.text.startsWith("Exits:")).length'), 70, 'World 3 includes all seventy room exit references');
  assert.equal(await evaluate('GUIDES[2].sections.flatMap(s => s.blocks).filter(b => b.text.startsWith("Named travel control:")).length'), 4, "World 3 names both ends of its stairs and inspection lift");
  assert.equal(await evaluate('GUIDES[2].sections.flatMap(s => s.blocks).filter(b => b.text.startsWith("Exits:")).some(b => /\\b(northeast|northwest|southeast|southwest) →/.test(b.text))'), false, 'World 3 room references contain no diagonals');
  await evaluate('showSection(GUIDES[2].sections.findIndex(s => s.title.includes("Arrival: Under the Radar")))');
  await waitFor('restoring === false && document.querySelector("input[data-step]") !== null');
  const world3Step = await evaluate('document.querySelector("input[data-step]").dataset.step');
  await evaluate('document.querySelector("input[data-step]").click()');
  await send('Page.reload');
  await waitFor('typeof world !== "undefined" && world === 3 && document.querySelector("input[data-step]")?.checked === true');
  assert.equal(await evaluate(`JSON.parse(localStorage.getItem(STORE)).worlds['3-rebuilt-2026-11-07'].checked.includes('${world3Step}')`), true, 'World 3 saved checklist');
  await send('Page.navigate', { url: url.replace(/#.*$/, '') + '#world-4/' });
  await waitFor('typeof world !== "undefined" && world === 4 && document.querySelector("#article h2") !== null');
  assert.equal(await evaluate('GUIDES[3].sections.flatMap(s => s.blocks).filter(b => b.text.startsWith("Exits:")).length'), 74, 'World 4 includes every room');
  assert.equal(await evaluate('GUIDES[3].sections.filter(s => s.title.includes("Journal checklist")).length'), 1);
  await evaluate('showSection(GUIDES[3].sections.findIndex(s => s.title.includes("Secure the landing")))');
  await waitFor('restoring === false && document.querySelector("input[data-step]") !== null');
  const world4Step = await evaluate('document.querySelector("input[data-step]").dataset.step');
  await evaluate('document.querySelector("input[data-step]").click()');
  assert.equal(await evaluate(`JSON.parse(localStorage.getItem(STORE)).worlds[4].checked.includes('${world4Step}')`), true, 'World 4 saves independent progress');
  assert.equal(await evaluate(`JSON.parse(localStorage.getItem(STORE)).worlds['3-rebuilt-2026-11-07'].checked.includes('${world3Step}')`), true, 'World 4 does not clear World 3 progress');
  assert.equal(await evaluate('JSON.stringify([state.worlds[1],state.worlds[2],state.worlds[3]])'), preservedProgress, 'Worlds 1/2 and legacy World 3 progress preserved');
  await evaluate('switchWorld(1)');
  assert.equal(await evaluate('document.documentElement.scrollWidth <= innerWidth'), true, 'desktop has no horizontal overflow');
  const desktopShot = await send('Page.captureScreenshot', { format: 'png' });
  const desktopScreenshot = path.join(profile, 'desktop.png');
  await writeFile(desktopScreenshot, Buffer.from(desktopShot.data, 'base64'));
  await evaluate('showSection(2)');
  await waitFor('document.querySelector("input[data-step]") !== null');
  await waitFor('restoring === false');
  const firstStep = await evaluate('document.querySelector("input[data-step]").dataset.step');
  await evaluate('document.querySelector("input[data-step]").click()');
  assert.equal(await evaluate(`JSON.parse(localStorage.getItem(STORE)).worlds[1].checked.includes('${firstStep}')`), true, 'checkmarks saved');
  await evaluate('window.scrollTo(0, 650)');
  await new Promise(resolve => setTimeout(resolve, 350));
  await send('Page.reload');
  await waitFor('document.querySelector("input[data-step]")?.checked === true');
  await waitFor('window.scrollY > 500');
  await evaluate('document.querySelector("#search").value="Chime"; document.querySelector("#search").dispatchEvent(new Event("input"))');
  assert.equal(await evaluate('document.querySelectorAll("#results button").length > 0'), true, 'search returns matches');
  await evaluate(`document.querySelector('[data-result-world="2"]').click()`);
  await waitFor('world === 2 && document.querySelector("#search-results").hidden');
  assert.equal(await evaluate(`document.querySelector('[data-world="2"]').getAttribute('aria-pressed')`), 'true', 'cross-world search navigation');
  await evaluate('document.querySelector("#theme").click()');
  assert.equal(await evaluate('document.documentElement.classList.contains("light")'), true, 'theme toggle');
  await evaluate('document.querySelector("#theme").click()');
  await send('Emulation.setDeviceMetricsOverride', { width: 390, height: 844, deviceScaleFactor: 1, mobile: true });
  await evaluate('document.querySelector("#contents").open=false; window.scrollTo(0,0)');
  assert.equal(await evaluate('document.documentElement.scrollWidth <= innerWidth'), true, 'mobile has no horizontal overflow');
  const shot = await send('Page.captureScreenshot', { format: 'png' });
  const screenshot = path.join(profile, 'mobile.png');
  await writeFile(screenshot, Buffer.from(shot.data, 'base64'));
  await send('Emulation.setDeviceMetricsOverride', { width: 320, height: 740, deviceScaleFactor: 1, mobile: true });
  assert.equal(await evaluate('document.documentElement.scrollWidth <= innerWidth'), true, 'narrow phone has no horizontal overflow');
  await evaluate('switchWorld(3); showSection(1)');
  await waitFor('restoring === false');
  assert.equal(await evaluate('document.documentElement.scrollWidth <= innerWidth'), true, 'World 3 narrow phone layout');
  const world3Shot = await send('Page.captureScreenshot', { format: 'png' });
  const world3Screenshot = path.join(profile, 'world3-mobile.png');
  await writeFile(world3Screenshot, Buffer.from(world3Shot.data, 'base64'));
  await waitFor('document.querySelector("#offline").textContent.includes("Ready")');
  await evaluate('switchWorld(4); showSection(GUIDES[3].sections.findIndex(s => s.title.includes("Crucible:"))); document.querySelector("#contents").open=false; window.scrollTo(0,0)');
  assert.equal(await evaluate('document.documentElement.scrollWidth <= innerWidth'), true, 'World 4 narrow phone layout');
  const world4Shot = await send('Page.captureScreenshot', { format: 'png' });
  const world4Screenshot = path.join(profile, 'world4-mobile.png');
  await writeFile(world4Screenshot, Buffer.from(world4Shot.data, 'base64'));
  await send('Network.enable');
  await send('Network.emulateNetworkConditions', { offline: true, latency: 0, downloadThroughput: 0, uploadThroughput: 0 });
  await send('Page.reload');
  await waitFor('document.querySelector("#article h2") !== null');
  assert.equal(await evaluate('GUIDES.length'), 4, 'all four worlds available after offline reload');
  assert.deepEqual(errors, [], 'no uncaught browser errors');
  console.log(JSON.stringify({ passed: ['World 4 direct link, all rooms and saved checklist', 'rebuilt World 3 direct link and saved checklist', 'World 2 root link', 'current Botanist return task', 'logo loaded', 'desktop layout', 'checkmarks persist', 'position restored', 'search', 'cross-world navigation', 'theme', 'mobile layout', 'offline reload', 'no browser errors'], screenshot, desktopScreenshot, world3Screenshot, world4Screenshot }, null, 2));
  await send('Browser.close');
} finally { socket?.close(); chrome.kill(); }
